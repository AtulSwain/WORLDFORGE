"use client";

import { useRouter } from "next/navigation";
import { useState, useTransition } from "react";
import { Sparkles, Check, X, Info } from "lucide-react";
import { toast } from "sonner";
import { acceptCharacterSuggestionAction, rejectSuggestionAction, requestCharacterSuggestionAction } from "@/server/actions/ai";
import { Button } from "@/components/ui/button";
import { Badge } from "@/components/ui/badge";
import { Textarea, NativeSelect } from "@/components/ui/input";
import { ListInput, type PickOption } from "@/components/ui/pickers";
import { Field, FormError } from "@/components/ui/field";
import { BUILTIN_RELATIONSHIP_KEYS, BUILTIN_RELATIONSHIP_TYPES } from "@/domain/catalog";

const ACTIONS = [
  { kind: "CHARACTER_TRAITS", label: "Suggest personality traits" },
  { kind: "CHARACTER_BACKSTORY", label: "Expand backstory" },
  { kind: "CHARACTER_MOTIVATIONS", label: "Generate motivations" },
  { kind: "CHARACTER_CONTRADICTIONS", label: "Identify contradictions" },
  { kind: "CHARACTER_RELATIONSHIPS", label: "Suggest relationships" },
] as const;

type Suggestion = { id: string; kind: string; output: unknown; isDemo: boolean; model: string };

/**
 * AI suggestions arrive as editable previews. Nothing is written until the creator
 * reviews, optionally edits, and accepts — and the write goes through normal validation.
 */
export function AiAssistPanel({
  worldId,
  entityId,
  entityVersion,
  ai,
  canUse,
  entityOptions,
}: {
  worldId: string;
  entityId: string;
  entityVersion: number;
  ai: { available: boolean; demo: boolean };
  canUse: boolean;
  entityOptions: PickOption[];
}) {
  const router = useRouter();
  const [s, setS] = useState<Suggestion | null>(null);
  const [draft, setDraft] = useState<Record<string, unknown> | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [pending, start] = useTransition();
  const [busyKind, setBusyKind] = useState<string | null>(null);

  if (!ai.available) {
    return (
      <div className="wf-panel p-4">
        <h2 className="flex items-center gap-2 text-sm font-medium"><Sparkles className="size-4 text-violet" /> AI assistance</h2>
        <p className="mt-2 text-xs text-text-2">AI is not configured on this server, so these tools are unavailable. Everything else — including deterministic consistency checks — works without it. Administrators can set <code className="text-text">AI_PROVIDER</code> and <code className="text-text">AI_API_KEY</code>.</p>
      </div>
    );
  }
  if (!canUse) return null;

  const request = (kind: string) =>
    start(async () => {
      setError(null);
      setBusyKind(kind);
      const r = await requestCharacterSuggestionAction(worldId, entityId, kind);
      setBusyKind(null);
      if (!r.ok) return setError(r.error);
      setS(r.data as Suggestion);
      setDraft(JSON.parse(JSON.stringify(r.data.output)) as Record<string, unknown>);
    });

  const accept = () =>
    start(async () => {
      if (!s || !draft) return;
      const r = await acceptCharacterSuggestionAction(worldId, entityId, s.id, draft, entityVersion);
      if (!r.ok) return setError(r.error);
      toast.success(s.kind === "CHARACTER_CONTRADICTIONS" ? "Review recorded" : "Suggestion applied — recorded in revision history");
      setS(null);
      setDraft(null);
      router.refresh();
    });

  const reject = () =>
    start(async () => {
      if (!s) return;
      await rejectSuggestionAction(worldId, s.id);
      setS(null);
      setDraft(null);
    });

  const names = new Map(entityOptions.map((o) => [o.id, o.name]));

  return (
    <div className="wf-panel p-4">
      <h2 className="flex items-center gap-2 text-sm font-medium">
        <Sparkles className="size-4 text-violet" /> AI assistance
        {ai.demo ? <Badge tone="violet">demo samples</Badge> : null}
      </h2>
      <p className="mt-1 text-xs text-muted">Grounded in this character&apos;s approved canon. Suggestions are previews until you accept them.</p>
      {!s ? (
        <div className="mt-3 flex flex-col gap-1.5">
          {ACTIONS.map((a) => (
            <Button key={a.kind} variant="secondary" size="sm" className="justify-start" disabled={pending} onClick={() => request(a.kind)}>
              <Sparkles className="text-violet" /> {busyKind === a.kind ? "Thinking…" : a.label}
            </Button>
          ))}
        </div>
      ) : null}
      <div className="mt-3"><FormError message={error} /></div>
      {s && draft ? (
        <div className="mt-3 flex flex-col gap-3 rounded-lg border border-violet/40 bg-violet/5 p-3">
          <div className="flex items-center gap-2 text-xs text-[#b9afdc]">
            <Info className="size-3.5" /> {s.isDemo ? "Demo sample output — not generated by a model." : `Unapproved suggestion from ${s.model}. Edit before accepting.`}
          </div>
          {s.kind === "CHARACTER_TRAITS" ? (
            <>
              <Field label="Personality"><Textarea rows={3} value={String(draft.personality ?? "")} onChange={(e) => setDraft({ ...draft, personality: e.target.value })} /></Field>
              {(["strengths", "flaws", "values", "fears"] as const).map((k) => (
                <Field key={k} label={k[0]!.toUpperCase() + k.slice(1)}><ListInput value={(draft[k] as string[]) ?? []} onChange={(v) => setDraft({ ...draft, [k]: v })} /></Field>
              ))}
            </>
          ) : s.kind === "CHARACTER_BACKSTORY" ? (
            <Field label="Backstory"><Textarea rows={10} value={String(draft.backstory ?? "")} onChange={(e) => setDraft({ ...draft, backstory: e.target.value })} /></Field>
          ) : s.kind === "CHARACTER_MOTIVATIONS" ? (
            <>
              <Field label="Motivations"><ListInput value={(draft.motivations as string[]) ?? []} onChange={(v) => setDraft({ ...draft, motivations: v })} /></Field>
              <Field label="Goals"><Textarea rows={4} value={String(draft.goals ?? "")} onChange={(e) => setDraft({ ...draft, goals: e.target.value })} /></Field>
            </>
          ) : s.kind === "CHARACTER_CONTRADICTIONS" ? (
            <ul className="flex flex-col gap-2 text-sm">
              {((draft.issues as { title: string; explanation: string }[]) ?? []).length === 0 ? <li className="text-text-2">No contradictions found.</li> : null}
              {((draft.issues as { title: string; explanation: string; references: string[] }[]) ?? []).map((i, n) => (
                <li key={n} className="rounded-md bg-bg-2 p-2">
                  <div className="font-medium">{i.title}</div>
                  <div className="text-xs text-text-2">{i.explanation}</div>
                  {i.references.length ? <div className="mt-1 text-2xs text-muted">Refers to: {i.references.map((r) => names.get(r) ?? "unknown record").join(", ")}</div> : null}
                </li>
              ))}
            </ul>
          ) : s.kind === "CHARACTER_RELATIONSHIPS" ? (
            <ul className="flex flex-col gap-2">
              {((draft.suggestions as { targetId: string; type: string; description: string; reasoning: string }[]) ?? []).map((r, n, arr) => (
                <li key={n} className="flex flex-col gap-1.5 rounded-md bg-bg-2 p-2 text-sm">
                  <div className="flex items-center gap-2">
                    <NativeSelect aria-label="Relationship type" value={r.type} onChange={(e) => { const next = [...arr]; next[n] = { ...r, type: e.target.value }; setDraft({ ...draft, suggestions: next }); }} className="h-8 w-40">
                      {BUILTIN_RELATIONSHIP_KEYS.map((k) => <option key={k} value={k}>{BUILTIN_RELATIONSHIP_TYPES[k].label}</option>)}
                    </NativeSelect>
                    <span className="flex-1 truncate">{names.get(r.targetId) ?? <em className="text-[#e7a3a3]">unknown record (will be rejected)</em>}</span>
                    <Button variant="ghost" size="icon-sm" aria-label="Drop suggestion" onClick={() => setDraft({ ...draft, suggestions: arr.filter((_, j) => j !== n) })}><X /></Button>
                  </div>
                  <span className="text-xs text-text-2">{r.reasoning}</span>
                </li>
              ))}
            </ul>
          ) : null}
          <div className="flex justify-end gap-2">
            <Button variant="ghost" size="sm" onClick={reject} disabled={pending}><X /> Reject</Button>
            <Button variant="primary" size="sm" onClick={accept} disabled={pending}><Check /> {s.kind === "CHARACTER_CONTRADICTIONS" ? "Acknowledge" : "Accept into canon"}</Button>
          </div>
        </div>
      ) : null}
    </div>
  );
}
